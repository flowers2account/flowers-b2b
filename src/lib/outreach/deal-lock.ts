// Сериализация обработки конкурентных входящих ОДНОГО диалога по dealId (amoCRM
// lead id). Общий для школьной кампании (campaign-handoff.ts) и LAPS
// (laps-handoff.ts) — механизм идентичный, баг потенциально в обеих.
//
// Причина (инцидент 05.09.2026): человек присылает два сообщения подряд за
// 2–3 сек ("ааа понятно" + "спасибо"). Umnico доставляет их как ДВА разных
// message.incoming (разные messageId — это НЕ ретрай). Оба вебхука
// обрабатываются параллельно в одном event loop, оба вызывают
// onLapsContactReplied на один dealId, оба независимо читают стадию сделки
// через getLead ДО того, как другой успел её сменить (TOCTOU на alreadySent) —
// и оба отправляют презентацию + каталог.
//
// Здесь: Map<dealId, Promise> как per-deal мьютекс. Второй вызов на тот же
// dealId ДОЖИДАЕТСЯ завершения первого (его исход игнорируется — своя ошибка
// не должна блокировать очередь), затем выполняется сам. Ошибка fn
// пробрасывается ВЫЗЫВАЮЩЕМУ, но не «застревает» в цепочке.
//
// Лок живёт только в памяти инстанса: при рестарте / в кластере (pm2 cluster)
// не переживает и между воркерами не общий. Окно гонки — секунды, поэтому для
// практической защиты от дублей этого достаточно; полная защита потребовала бы
// внешнего лока (Redis/БД), что здесь избыточно.

const chain = new Map<number, Promise<unknown>>()

export async function withDealLock<T>(dealId: number, fn: () => Promise<T>): Promise<T> {
  const prev = chain.get(dealId) ?? Promise.resolve()
  // следующий в очереди дожидается предыдущего; чужой исход/ошибку глотаем
  const run = prev.catch(() => {}).then(fn)
  chain.set(dealId, run)
  try {
    return await run
  } finally {
    // ключ снимаем, только если за время выполнения никто не встал следом
    if (chain.get(dealId) === run) chain.delete(dealId)
  }
}

/** Для тестов: сколько диалогов сейчас «в работе». */
export function dealLockSize(): number {
  return chain.size
}
