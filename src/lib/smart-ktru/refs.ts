export function regionLabel(kato: string | null | undefined): string {
  if (!kato || !kato.trim()) return 'Регион не указан'
  const pref = kato.slice(0, 2)
  return KATO_REGION[pref] ?? `КАТО ${kato}`
}

export function lotStatusLabel(id: number | null | undefined): string {
  return id == null ? '—' : LOT_STATUS[id] ?? `статус ${id}`
}
export function tradeMethodLabel(id: number | null | undefined): string {
  return id == null ? '—' : TRADE_METHOD[id] ?? `способ ${id}`
}

