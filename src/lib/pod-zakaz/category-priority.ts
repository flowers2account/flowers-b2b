// Порядок вкладок категорий на витрине «Под заказ» — фиксированный, по смыслу для флориста:
// сначала живые цветы/срезка, потом растения, потом упаковка, потом декор, потом остальное.
// НЕ по количеству товаров (прыгало бы между прогонами синка) и НЕ чистый алфавит (не имеет
// смысла для покупателя). Ключ — ТОЧНОЕ значение nomenclature_name с сайта Proflowers.
//
// Шаг 10 между смысловыми блоками — чтобы новую ПОДТВЕРЖДЁННУЮ категорию можно было воткнуть
// в нужную группу, не переставляя остальные записи. Незнакомое название (категория, которую
// ещё не видели в синке) просто уходит в конец списка по алфавиту — порядок не ломается,
// вкладка появится, просто последней, пока её сюда не допишут.
const CATEGORY_PRIORITY: Record<string, number> = {
  // 0-9   — живые цветы / срезка (пока не встречали среди активных дней Proflowers)
  // 10-19 — растения
  'Комнатные растения': 10,
  // 20-29 — упаковка / флористическая расходка (пока не встречали)
  // 30-39 — декор
  'Товары декора': 30,
  // 40+   — остальное, по мере появления новых nomenclature_name дописывать сюда
}

const UNKNOWN_CATEGORY_PRIORITY = 1000

export function sortCategoryNames(names: string[]): string[] {
  return [...names].sort((a, b) => {
    const pa = CATEGORY_PRIORITY[a] ?? UNKNOWN_CATEGORY_PRIORITY
    const pb = CATEGORY_PRIORITY[b] ?? UNKNOWN_CATEGORY_PRIORITY
    if (pa !== pb) return pa - pb
    return a.localeCompare(b, 'ru')
  })
}
