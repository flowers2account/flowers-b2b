export const CAMPAIGN_CLASSIFY_PROMPT = `Определи намерение последнего сообщения клиента с учётом истории
диалога. Ответь СТРОГО в формате JSON без каких-либо пояснений:
{"intent":"ЗНАЧЕНИЕ"}

Допустимые значения ЗНАЧЕНИЕ (ровно одно из списка, без синонимов):
greeting, what_is_it, agree_send, refuse, procurement, postponed, confirmed_forwarded, other

Правила:
- greeting — только если это первое содержательное сообщение диалога
  И в истории ещё нет ни одного сообщения от бота. Если бот уже отвечал
  раньше — даже повторное "Здравствуйте" от клиента НЕ greeting, а other
  (если не подходит под другие категории).
- what_is_it — клиент спрашивает, кто вы, зачем написали, что предлагаете.
- agree_send — явное согласие получить/переслать материал: "да",
  "пришлите", "конечно", "скидывайте" и подобное по смыслу.
- refuse — отказ, просьба не писать, негативная реакция.
- procurement — вопрос по смыслу связан с закупкой школы, тендером,
  госзакупкой, лотом, конкурсом, поставщиком — определяй по смыслу,
  не только по наличию конкретного слова.
- postponed — клиент не отказывается, но просит вернуться к разговору
  позже и не отвечает по существу сейчас: "давайте позже", "напишите
  завтра", "я посмотрю на неделе", "сейчас некогда", "ближе к выходным".
  Просьба подождать с конкретной датой или временем — это тоже postponed
  (отдельной обработки даты сейчас нет).
- confirmed_forwarded — клиент подтверждает, что УЖЕ переслал полученный
  материал родителям или в родительскую группу: "переслал", "отправила
  в чат", "скинул родителям", "готово, разместила". Отличать от
  agree_send: там клиент только соглашается получить материал, здесь —
  уже разослал его сам.
- other — всё остальное.`

